"""fig5：T0（三折均值）逐帧 R² 的分解——相关 r²/Spearman（无幅值）、幅值比 α、NMAE。数据来自 frame_r2_decomposition_best.csv。"""
import csv, numpy as np, matplotlib
matplotlib.use('Agg'); import matplotlib.pyplot as plt
plt.rcParams.update({'font.family': 'sans-serif', 'font.sans-serif': ['DejaVu Sans'], 'axes.unicode_minus': False})
rows = list(csv.DictReader(open('frame_r2_decomposition_best.csv')))
steps = sorted({int(r['step']) for r in rows})
def mean(arm, k): return np.array([np.nanmean([float(r[k]) for r in rows if r['arm'] == arm and int(r['step']) == s]) for s in steps])
q = mean('T0', 'q_norm')
fig, ax = plt.subplots(3, 1, figsize=(9, 9), sharex=True)
for a in ax: a.fill_between(steps, 0, 1.05, where=q < np.sort(q)[20], color='0.9', transform=a.get_xaxis_transform(), label='trough (20 lowest-Q frames)')
ax[0].plot(steps, mean('T0', 'r2cb'), 'k-', lw=2, label='R2_cb (penalises amplitude + bias)')
ax[0].plot(steps, mean('T0', 'r2_fit'), 'C0-', lw=1.5, label='r2 = Pearson r squared (scale/offset free)')
ax[0].plot(steps, mean('T0', 'spearman'), 'C2--', lw=1.5, label='Spearman rho (rank, fully scale-free)')
ax[0].plot(steps, mean('T0', 'ccc'), 'C3:', lw=1.5, label='Lin CCC = r x amplitude/bias agreement')
ax[0].set_ylim(0, 1); ax[0].set_ylabel('T0, mean of 3 folds'); ax[0].legend(loc='lower left', fontsize=8, ncol=2)
ax[1].plot(steps, mean('T0', 'alpha'), 'C1-', lw=2, label='alpha = sd(pred)/sd(true)  (amplitude ratio)')
ax[1].plot(steps, mean('T0', 'r'), 'C0--', lw=1, label='r  (MSE-optimal alpha equals r)')
ax[1].plot(steps, mean('T0', 'top10_ratio'), 'C4:', lw=1, label='top10 pred/true ratio')
ax[1].set_ylim(0, 1); ax[1].legend(loc='lower left', fontsize=8)
ax[2].plot(steps, mean('T0', 'nmae_range') * 100, 'C5-', lw=2, label='NMAE_range %  = MAE / (max - min of truth)')
ax[2].plot(steps, mean('T0', 'nmae_casemean') * 100, 'C6-', lw=1.5, label='per-case NMAE_range mean %')
ax[2].plot(steps, mean('T0', 'nrmse_mean') * 10, 'C7--', lw=1, label='NRMSE_mean x10 %  = RMSE / mean of truth')
axq = ax[2].twinx(); axq.plot(steps, q, color='0.5', lw=0.8); axq.set_ylabel('Q/Q_peak', color='0.5'); axq.set_ylim(0, 1.05)
ax[2].set_ylim(0, 16); ax[2].legend(loc='upper left', fontsize=8); ax[2].set_xlabel('Fluent step (1120...1280, dt = 10 ms)')
fig.suptitle('WSS T0 (phase query), per-frame decomposition: the R2 drop is mostly a drop in correlation itself, not amplitude', fontsize=11)
fig.tight_layout(); fig.savefig('fig5_r2_decomposition.png', dpi=150); fig.savefig('fig5_r2_decomposition.svg'); print('saved fig5')
